SELECT DISTINCT Value
FROM
(
    SELECT LTRIM(RTRIM(/*COLUMN_NAME*/)) AS Value
    FROM dbo.ImportedTransaction
    WHERE /*COLUMN_NAME*/ IS NOT NULL AND LTRIM(RTRIM(/*COLUMN_NAME*/)) <> N''
    UNION
    SELECT LTRIM(RTRIM(/*COLUMN_NAME*/)) AS Value
    FROM dbo.RecurringBill
    WHERE /*COLUMN_NAME*/ IS NOT NULL AND LTRIM(RTRIM(/*COLUMN_NAME*/)) <> N''
) AS valueset
ORDER BY Value;
