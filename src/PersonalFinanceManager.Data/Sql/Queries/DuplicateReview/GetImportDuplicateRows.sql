SELECT TOP (/*MAX_ROWS*/)
    CAST(N'/*REVIEW_KIND*/' AS nvarchar(30)) AS ReviewKind,
    CAST(NULL AS bigint) AS CrossAccountDuplicateReviewId,
    r.ImportRowId,
    r.ImportBatchId,
    r.RowNumber,
    r.[Status],
    r.DuplicateConfidence,
    r.DuplicateReason,
    b.ImportProfileCode,
    b.OriginalFileName,
    b.AccountId,
    a.AccountNickname,
    r.AcceptedTransactionId AS CandidateTransactionId,
    a.AccountNickname AS CandidateAccountNickname,
    r.TransactionDate AS CandidateDate,
    r.PostingDate AS CandidatePostingDate,
    r.TransactionTime AS CandidateTime,
    r.Amount AS CandidateAmount,
    r.[Type] AS CandidateType,
    r.[Description] AS CandidateDescription,
    r.ExternalTransactionId AS CandidateExternalTransactionId,
    r.FundingSource AS CandidateFundingSource,
    r.SourceCategory AS CandidateSourceCategory,
    r.Memo AS CandidateMemo,
    r.Category AS CandidateCategory,
    r.SpendingClass AS CandidateCategoryType,
    r.Merchant AS CandidateMerchant,
    r.IsIncome AS CandidateIsIncome,
    r.IsTransfer AS CandidateIsTransfer,
    existing.ImportedTransactionId AS ExistingTransactionId,
    existingAccount.AccountNickname AS ExistingAccountNickname,
    existing.TransactionDate AS ExistingDate,
    existing.PostingDate AS ExistingPostingDate,
    existing.TransactionTime AS ExistingTime,
    existing.Amount AS ExistingAmount,
    existing.[Type] AS ExistingType,
    existing.[Description] AS ExistingDescription,
    existing.ExternalTransactionId AS ExistingExternalTransactionId,
    existing.FundingSource AS ExistingFundingSource,
    existing.SourceCategory AS ExistingSourceCategory,
    existing.Memo AS ExistingMemo,
    existing.Category AS ExistingCategory,
    existing.SpendingClass AS ExistingCategoryType,
    existing.Merchant AS ExistingMerchant,
    existing.IsIncome AS ExistingIsIncome,
    existing.IsTransfer AS ExistingIsTransfer,
    r.CreatedAtUtc
FROM dbo.ImportRow AS r
INNER JOIN dbo.ImportBatch AS b ON b.ImportBatchId = r.ImportBatchId
INNER JOIN dbo.Account AS a ON a.AccountId = b.AccountId
LEFT JOIN dbo.ImportedTransaction AS existing ON existing.ImportedTransactionId = r.DuplicateMatchTransactionId
LEFT JOIN dbo.Account AS existingAccount ON existingAccount.AccountId = existing.AccountId
/*WHERE_CLAUSE*/
ORDER BY r.CreatedAtUtc DESC, r.ImportRowId DESC;
